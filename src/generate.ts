// The spec as plain Playwright: a class per page (pages/), a component object
// per layout and dialog, a test per journey (tests/, as the spec's folders
// are), each step a `test.step` and each line one of its own, so a failure
// names the line of the spec that failed. Nothing here needs pomspec to run.
//
// With POM_SHOTS (`pom shots`), a test also pictures its journey's moments: its
// start, then the screen after each acting line, once the lines after it have
// seen it settle (moments.ts). Each picture goes to `.pom/run/` through
// `toHaveScreenshot` (it waits for two still frames and hides the video's
// captions); `pom shots` keeps the journey only when every width passed. A
// `video-<width>` project plays the journey again, recorded, at a person's pace; with
// POM_VIDEOS too (`pom videos`), as a video for pomspec, by pom's own reel (reel.ts),
// the one thing a test loads of pom's, and only then.

const HEADER = "// Generated by pom from the spec. Edit the spec, not this file.\n";

/** What `generate` writes, and so all it ever removes: the run, the cache and the videos stay. */
const OWN = ["pages", "tests", "journeys", "pom.ts", "playwright.config.ts", ".gitignore"];

const fields = (model: ObjectModel) =>
  model.controls.map((c) => `  readonly ${c.property}: Locator;`);
const assigns = (model: ObjectModel) =>
  model.controls.map((c) => `    this.${c.property} = ${c.locator};`);

function pathPattern(page: Page): string {
  const body = page.segments
    .map((segment) =>
      segment.startsWith("[") ? "[^/?#]+" : segment.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&"),
    )
    .join("\\/");
  return `/^https?:\\/\\/[^/]+\\/${body}${body ? "\\/?" : ""}(?:[?#].*)?$/`;
}

function pageFile(page: Page): string {
  const model = pageModel(page);
  const params = page.segments.filter((s) => s.startsWith("[")).map((s) => s.slice(1, -1));
  // A segment's name is a key, quoted: `[project-id]` is `params["project-id"]`.
  const url = `/${page.segments.map((s) => (s.startsWith("[") ? `\${params[${JSON.stringify(s.slice(1, -1))}]}` : s)).join("/")}`;
  const imports = [
    ...page.layouts.map((l) => `import { ${l.className} } from "./${l.className}.ts";`),
    ...page.dialogs.map((d) => `import { ${d.className} } from "./${d.className}.ts";`),
  ];
  return `${HEADER}import { expect, type Locator, type Page } from "@playwright/test";
${imports.join("\n")}${imports.length ? "\n" : ""}
/** ${page.route} */
export class ${page.className} {
  readonly page: Page;
${[
  ...page.layouts.map((l) => `  readonly ${layoutProperty(l)}: ${l.className};`),
  ...page.dialogs.map((d) => `  readonly ${d.property}: ${d.className};`),
  ...fields(model),
].join("\n")}

  constructor(page: Page) {
    this.page = page;
${[
  ...page.layouts.map((l) => `    this.${layoutProperty(l)} = new ${l.className}(page);`),
  ...page.dialogs.map((d) => `    this.${d.property} = new ${d.className}(page);`),
  ...assigns(model),
].join("\n")}
  }

  async goto(${params.length ? `params: { ${params.map((p) => `${JSON.stringify(p)}: string`).join("; ")} }` : ""}) {
    await this.page.goto(${params.length ? `\`${url}\`` : JSON.stringify(url)});
    await this.expectLoaded();
  }

  /** At this page. What is on it, each control's own step finds. */
  async expectLoaded() {
    await expect(this.page).toHaveURL(${pathPattern(page)});
  }
}
`;
}

