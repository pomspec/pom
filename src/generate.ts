/** A width's Playwright options, from a device or a desktop's. */
function widthUse(config: Config, name: string): string {
  const width = config.widths[name]!;
  const base = width.device
    ? `devices[${JSON.stringify(width.device)}]`
    : `devices["Desktop Chrome"]`;
  const own = {
    ...(width.viewport ? { viewport: width.viewport } : {}),
    ...(width.deviceScaleFactor !== undefined
      ? { deviceScaleFactor: width.deviceScaleFactor }
      : {}),
    ...(width.isMobile !== undefined ? { isMobile: width.isMobile } : {}),
    ...(width.hasTouch !== undefined ? { hasTouch: width.hasTouch } : {}),
  };
  return `{ ...${base}, ...${JSON.stringify(own)} }`;
}

function playwrightConfig(config: Config, reporter: string): string {
  const widths = Object.keys(config.widths);
  const projects = [
    ...widths.map(
      (name) => `    { name: ${JSON.stringify(name)}, use: ${widthUse(config, name)} },`,
    ),
    // Recorded without a trace: tracing's screenshots would start the page's capture first, at 800px.
    ...(config.video?.widths ?? []).map(
      (name) =>
        `    { name: ${JSON.stringify(`video-${name}`)}, use: { ...${widthUse(config, name)}, trace: "off" } },`,
    ),
  ];
  // The app's own server; a base run starts the base's on a port of its own ($PORT).
  const web = config.webServer;
  const server = web
    ? `
  webServer: {
    command: ${JSON.stringify(web.command)},
    cwd: ${JSON.stringify(path.resolve(config.dir, web.cwd ?? "."))},
    env: { ...${JSON.stringify(web.env ?? {})}, ...(process.env.PORT ? { PORT: process.env.PORT } : {}) },
    reuseExistingServer: ${web.reuseExistingServer ?? true},
    timeout: ${web.timeout ?? 60_000},
    ${web.url || !web.port ? `url: process.env.PORT ? ${JSON.stringify(`http://localhost:`)} + process.env.PORT : ${JSON.stringify(web.url ?? config.baseURL ?? "")},` : `port: process.env.PORT ? Number(process.env.PORT) : ${web.port},`}
  },`
    : "";
  return `${HEADER}import { defineConfig, devices } from "@playwright/test";

// \`pom shots\` reports through pom's own reporter (one line a journey and width),
// which also keeps \`toHaveScreenshot\`'s "writing actual" notes out of the output.
const shots = !!process.env.POM_SHOTS;
const ws = process.env.POM_WS;

export default defineConfig({
  expect: {
    toHaveScreenshot: {
      maxDiffPixelRatio: ${config.threshold.ratio},
      pathTemplate: "run/{arg}{ext}",
      threshold: ${config.threshold.pixel},
      timeout: 15_000,
    },
  },
  fullyParallel: false,
  outputDir: "./results",
  projects: [
${projects.join("\n")}
  ],
  reporter: shots ? [[${JSON.stringify(reporter)}]] : [["list"]],
  retries: 0,
  // \`pom map\` crawls with a test of its own, beside the journeys'.
  testDir: process.env.POM_TESTS ?? "./tests",
  timeout: 120_000,
  updateSnapshots: "changed",
  use: {
    baseURL: process.env.POM_BASE_URL,
    colorScheme: ${JSON.stringify(config.colorScheme)},
    locale: ${JSON.stringify(config.locale)},
    reducedMotion: "reduce",
    timezoneId: ${JSON.stringify(config.timezoneId)},
    trace: "retain-on-failure",
    ...(ws ? { connectOptions: { exposeNetwork: "<loopback>", wsEndpoint: ws } } : {}),
  },${server}
  // Journeys share one app: one at a time, so a reset or a list never sees another's.
  workers: 1,
});
`;
}

