export type GenerateOptions = Readonly<{
  check?: CheckOptions;
  config?: Config;
  /** Write what checks (every page, the journeys that pass) even when some do not. */
  partial?: boolean;
}>;

export function generate(
  spec: Spec,
  out: string,
  options: GenerateOptions = {},
): { problems: Array<Problem>; written: Array<string> } {
  const config = options.config ?? resolveConfig({}, path.dirname(spec.root), null);
  const check: CheckOptions = options.check ?? {
    signIns: new Set(Object.keys(config.roles)),
  };
  const { compiled, problems } = checkSpec(spec, check);
  if (problems.length && !options.partial) return { problems, written: [] };
  for (const own of OWN) rmSync(path.join(out, own), { force: true, recursive: true });
  const written: Array<string> = [];
  const write = (file: string, text: string) => {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
    written.push(file);
  };
  const layouts = new Map(spec.pages.flatMap((p) => p.layouts).map((l) => [l.className, l]));
  for (const layout of layouts.values())
    write(path.join(out, "pages", `${layout.className}.ts`), layoutFile(layout));
  for (const page of spec.pages) {
    write(path.join(out, "pages", `${page.className}.ts`), pageFile(page));
    for (const dialog of page.dialogs)
      write(path.join(out, "pages", `${dialog.className}.ts`), dialogFile(dialog));
  }
  for (const c of compiled) {
    const relative = path.relative(spec.root, c.journey.file).replace(/\.feature$/, ".spec.ts");
    const file = path.join(out, "tests", relative);
    write(file, testFile(c, spec, out, file, config.reset !== null));
  }
  // Every role's way in, used by a journey or not: \`pom map\` signs in with them too.
  const entries = new Set<Journey>([
    ...compiled.flatMap((c) => c.entries),
    ...[...spec.roles].flatMap((role) => {
      if (role === "visitor" || config.roles[role]) return [];
      const entry = entryFor(spec, role);
      return entry && compiled.some((c) => c.journey === entry) ? [entry] : [];
    }),
  ]);
  for (const entry of entries) {
    const played = compile(spec, entry, check).compiled!;
    write(path.join(out, "journeys", `${journeyFunction(entry)}.ts`), journeyFile(played, spec));
  }
  write(path.join(out, "pom.ts"), helpers(config));
  write(path.join(out, "playwright.config.ts"), playwrightConfig(config, REPORTER));
  // Nothing pom writes here is the repository's: the run, the pictures, the videos.
  write(path.join(out, ".gitignore"), "*\n");
  return { problems, written };
}
