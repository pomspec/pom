/** A string as the test writes it: single quotes when that spares escaping a Gherkin line's own. */
const quote = (text: string) =>
  text.includes('"') && !/['\\]/.test(text) ? `'${text}'` : JSON.stringify(text);

const lineStep = ({ code, line }: Call, indent: string) =>
  `${indent}await test.step(${quote(line.source)}, async () => {\n${indent}  ${code};\n${indent}});`;

/**
 * A line as the generated test tells `say()` of it, for `pom videos`' reel: its line in
 * the .feature, its verb, and what it acts on, or what a `Then` proves is on the
 * screen (from its assertion).
 */
function atOf(call: Call): string {
  const shown =
    call.target ??
    /^await expect\((.+?)\)\.(?:toBeVisible|toContainText)\(/.exec(call.code)?.[1] ??
    /^await (.+)\.expectOpen\(\)$/.exec(call.code)?.[1]?.concat(".root") ??
    null;
  return `{ line: ${call.line.line}, target: ${shown ? `() => ${shown}` : "null"}, verb: ${JSON.stringify(call.line.action.verb)} }`;
}

/** A moment as the generated test passes it to `moment()`: its static part. */
function momentCall(planned: Planned, indent: string): string {
  const { target, ...seen } = planned;
  const at = JSON.stringify({
    after: seen.after,
    id: seen.id,
    index: seen.index,
    journey: seen.journey,
    next: seen.next,
    page: seen.page,
    role: seen.role,
    state: seen.state,
    step: seen.step,
  });
  return `${indent}await moment(page, ${at}, ${target ? `() => ${target}` : "null"});`;
}

/**
 * A journey's lines as test steps; with its moments (a journey's own test), each
 * taken before the acting line it precedes, the last at the end, and the video's
 * captions and lines between them. An entry journey (a sign-in) has none.
 */
function body(
  compiled: Compiled,
  moments: ReadonlyArray<Planned & Readonly<{ before: Call | null }>> | null,
): Array<string> {
  const out: Array<string> = [];
  const before = new Map(moments?.flatMap((m) => (m.before ? [[m.before, m]] : [])) ?? []);
  const lines = (calls: ReadonlyArray<Call>, indent: string) => {
    for (const call of calls) {
      const planned = before.get(call);
      if (planned) out.push(momentCall(planned, indent));
      if (moments) out.push(`${indent}await say(page, ${quote(call.line.source)}, ${atOf(call)});`);
      out.push(lineStep(call, indent));
    }
  };
  for (const page of compiled.pages)
    out.push(`  const ${pageVariable(page)} = new ${page.className}(page);`);
  if (compiled.background.length) {
    out.push(`  await test.step("Background", async () => {`);
    lines(compiled.background, "    ");
    out.push(`  });`);
  }
  // The video starts once the journey's own steps do: a sign-in played first is not its story.
  if (moments) out.push(`  await begin(page, ${JSON.stringify(moments[0]!.journey)});`);
  for (const step of compiled.steps) {
    out.push(`  await test.step(${JSON.stringify(step.caption)}, async () => {`);
    if (moments) out.push(`    await caption(page, ${JSON.stringify(step.caption)});`);
    lines(step.calls, "    ");
    out.push(`  });`);
  }
  const last = moments?.at(-1);
  if (last) {
    out.push(momentCall(last, "  "));
    out.push(`  await end(page);`);
  }
  return out;
}

const uses = (compiled: Compiled, call: string) =>
  [...compiled.background, ...compiled.steps.flatMap((s) => s.calls)].some((c) =>
    c.code.includes(`${call}(`),
  );

function imports(compiled: Compiled, up: string, extra: ReadonlyArray<string>): Array<string> {
  const helpers = [
    ...(uses(compiled, "unique") ? ["unique"] : []),
    ...(uses(compiled, "signIn") ? ["signIn"] : []),
    ...extra,
  ];
  return [
    ...compiled.pages.map((p) => `import { ${p.className} } from "${up}/pages/${p.className}.ts";`),
    ...compiled.entries.map(
      (j) => `import { ${journeyFunction(j)} } from "${up}/journeys/${journeyFunction(j)}.ts";`,
    ),
    ...(helpers.length ? [`import { ${helpers.sort().join(", ")} } from "${up}/pom.ts";`] : []),
  ];
}

/** A journey's id: its file, relative to the spec, without `.feature`. */
export const journeyId = (spec: Spec, journey: Journey) =>
  path
    .relative(spec.root, journey.file)
    .replace(/\.feature$/, "")
    .split(path.sep)
    .join("/");

function testFile(
  compiled: Compiled,
  spec: Spec,
  out: string,
  file: string,
  reset: boolean,
): string {
  const up = path.relative(path.dirname(file), out) || ".";
  const id = journeyId(spec, compiled.journey);
  const moments = plan(compiled, id);
  return `${HEADER}// ${path.relative(spec.root, compiled.journey.file)}
import { expect, test } from "@playwright/test";
${imports(compiled, up, ["begin", "caption", "end", "finish", "moment", ...(reset ? ["reset"] : []), "say"]).join("\n")}
${reset ? "\ntest.beforeEach(reset);\n" : ""}
test.afterEach(finish);

test(${JSON.stringify(compiled.journey.title)}, async ({ page }) => {
${body(compiled, moments).join("\n")}
});
`;
}

/** A journey another plays first, to sign in: the same steps, as a function. */
function journeyFile(compiled: Compiled, spec: Spec): string {
  return `${HEADER}// ${path.relative(spec.root, compiled.journey.file)}
import { expect, type Page, test } from "@playwright/test";
${imports(compiled, "..", []).join("\n")}

/** ${compiled.journey.title}: who it ends as is who it signs in. */
export async function ${journeyFunction(compiled.journey)}(page: Page) {
${body(compiled, null).join("\n")}
}
`;
}

